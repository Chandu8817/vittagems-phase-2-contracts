// Builds frontend/contracts.js from the forge artifacts (out/) and the latest local deployment
// (broadcast/DeployLocal.s.sol/31337/run-latest.json). Run after `make demo-deploy`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const broadcastPath = join(root, "broadcast", "DeployLocal.s.sol", "31337", "run-latest.json");

const CONTRACTS = [
  "AssetRegistry",
  "AssetApprovalDAO",
  "ReserveManager",
  "ProofOfReserve",
  "MockUSDC",
  "MockTreasury",
  "MockPriceFeed",
  "VittaStablecoin",
  "CollateralController",
  "ChainlinkPriceOracle",
  "RedemptionModule",
];

let broadcast;
try {
  broadcast = JSON.parse(readFileSync(broadcastPath, "utf8"));
} catch {
  console.error(`No local deployment found at ${broadcastPath}.\nStart anvil and run \`make demo-deploy\` first.`);
  process.exit(1);
}

const addresses = {};
for (const tx of broadcast.transactions) {
  if (tx.transactionType === "CREATE" && CONTRACTS.includes(tx.contractName)) {
    addresses[tx.contractName] = tx.contractAddress;
  }
}

const abis = {};
for (const name of CONTRACTS) {
  if (!addresses[name]) throw new Error(`${name} missing from ${broadcastPath}`);
  const artifact = JSON.parse(readFileSync(join(root, "out", `${name}.sol`, `${name}.json`), "utf8"));
  abis[name] = artifact.abi;
}

const out = `// Generated by frontend/export.mjs — do not edit.
export const DEPLOYED_AT_BLOCK = ${Number(broadcast.receipts?.[0]?.blockNumber ?? 0)};
export const ADDRESSES = ${JSON.stringify(addresses, null, 2)};
export const ABIS = ${JSON.stringify(abis)};
`;
writeFileSync(join(root, "frontend", "contracts.js"), out);
console.log("Wrote frontend/contracts.js");
for (const [name, addr] of Object.entries(addresses)) console.log(`  ${name.padEnd(22)} ${addr}`);
